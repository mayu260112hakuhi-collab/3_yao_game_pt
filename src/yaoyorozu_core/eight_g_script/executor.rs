// 実行側のファイル
use super::command::{命令, 命令種別};

// 命令の実行処理
pub fn 命令を実行(命令: 命令) {
    match 命令.動詞 {
        命令種別::表示 => println!("表示: {}", 命令.引数),
        命令種別::読む => println!("読み込み: {}", 命令.引数),
        命令種別::保存 => println!("保存: {}", 命令.引数),
        命令種別::作成 => println!("作成: {}", 命令.引数),
        命令種別::削除 => println!("削除: {}", 命令.引数),
        命令種別::リネーム => println!("リネーム: {}", 命令.引数),
        命令種別::設定 => println!("設定変更: {}", 命令.引数),
        命令種別::待機 => println!("待機: {} 秒", 命令.引数),
        命令種別::ドラッグ => println!("ドラッグ開始: {}", 命令.引数),
        命令種別::ドロップ => println!("ドロップ実行: {}", 命令.引数),
        命令種別::移動 => println!("移動先: {}", 命令.引数),
        命令種別::開く => println!("開く対象: {}", 命令.引数),
        命令種別::閉じる => println!("閉じる対象: {}", 命令.引数),
        命令種別::拡大 => println!("{} を拡大", 命令.引数),
        命令種別::縮小 => println!("{} を縮小", 命令.引数),
        命令種別::回転 => println!("{} を回転", 命令.引数),
        命令種別::座標 => println!("座標 {} を参照", 命令.引数),
        命令種別::取得 => println!("{} を取得", 命令.引数),
        命令種別::ディレクトリ内の画像を表示 => {
            println!("ディレクトリ読み込み中: {}", 命令.引数)
        }
        命令種別::ディレクトリの中身を取得 => {
            println!("ディレクトリの中身を取得: {}", 命令.引数)
        }
        命令種別::初期化 => println!("システム初期化"),
        命令種別::終了 => println!("プログラム終了"),
        // アクション用
        命令種別::ジャンプ => println!("ジャンプ！"),
        命令種別::加速 => println!("加速: {}", 命令.引数),
        命令種別::減速 => println!("減速: {}", 命令.引数),
        命令種別::衝突 => println!("衝突発生: {}", 命令.引数),
        命令種別::反射 => println!("反射処理: {}", 命令.引数),
        命令種別::追跡 => println!("追跡対象: {}", 命令.引数),
        命令種別::攻撃 => println!("攻撃実行: {}", 命令.引数),
        命令種別::被弾 => println!("被弾処理: {}", 命令.引数),
        命令種別::回復 => println!("回復処理: {}", 命令.引数),
        命令種別::無敵 => println!("無敵状態へ移行"),
        命令種別::発射 => println!("発射: {}", 命令.引数),
        命令種別::再生 => println!("アニメーション再生: {}", 命令.引数),
        命令種別::遷移 => println!("ステート遷移: {}", 命令.引数),
        // 制御・システム系
        命令種別::停止 => println!("一時停止"),
        命令種別::再開 => println!("再開"),
        命令種別::検索 => println!("検索: {}", 命令.引数),
        命令種別::置換 => println!("置換: {}", 命令.引数),
        命令種別::描画 => println!("描画処理"),
        命令種別::フェードイン => println!("フェードイン開始"),
        命令種別::フェードアウト => println!("フェードアウト開始"),
        命令種別::押下 => println!("キー押下: {}", 命令.引数),
        命令種別::通信 => println!("通信接続: {}", 命令.引数),
        命令種別::ログ出力 => println!("ログ: {}", 命令.引数),
        命令種別::その他(詳細) => println!("汎用命令: {}", 詳細),
    }
}
