// 解析側のファイル
use super::command::{命令, 命令種別};
use std::collections::HashMap;

pub fn 命令を解析(ソースコード: &str) -> 命令 {
    // 命令キーワードと種別のマッピングを作成
    let mut マップ = HashMap::new();
    マップ.insert("表示", 命令種別::表示);
    マップ.insert("ドラッグ", 命令種別::ドラッグ);
    マップ.insert("移動", 命令種別::移動);
    マップ.insert("読む", 命令種別::読む);
    マップ.insert("保存", 命令種別::保存);
    マップ.insert("作成", 命令種別::作成);
    マップ.insert("削除", 命令種別::削除);
    マップ.insert("リネーム", 命令種別::リネーム);
    マップ.insert("取得", 命令種別::取得);
    マップ.insert("ジャンプ", 命令種別::ジャンプ);
    マップ.insert("攻撃", 命令種別::攻撃);
    マップ.insert("再生", 命令種別::再生);
    マップ.insert("検索", 命令種別::検索);

    // ソースコードから動詞部分を抽出するロジック
    // 例: 「（引数）を動詞。」という形式を想定
    if let Some(開始位置) = ソースコード.find('（') {
        if let Some(終了位置) = ソースコード.find("）を") {
            let 引数 = ソースコード[開始位置 + 1..終了位置].replace("\"", "");
            let 残り = &ソースコード[終了位置 + 3..]; // "）を"の分をスキップ
            let 動詞 = 残り.trim_end_matches('。');

            // マップから動詞を探す
            if let Some(種別) = マップ.get(動詞) {
                return 命令 {
                    動詞: 種別.clone(), // 命令種別はCloneを導出しておく必要があります
                    引数,
                };
            }
        }
    }

    // マップにない場合のフォールバック
    panic!("不明な命令: {}", ソースコード);
}
