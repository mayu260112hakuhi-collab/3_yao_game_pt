use std::str::FromStr;

#[derive(Debug, Clone, PartialEq)]
pub enum 命令種別 {
    表示,
    読む,
    保存,
    作成,
    削除,
    リネーム,
    設定,
    待機,
    ドラッグ,
    ドロップ,
    移動,
    開く,
    閉じる,
    拡大,
    縮小,
    回転,
    座標,
    取得,
    ディレクトリ内の画像を表示,
    ディレクトリの中身を取得,
    初期化,
    終了,
    // アクション用
    ジャンプ,
    加速,
    減速,
    衝突,
    反射,
    追跡,
    攻撃,
    被弾,
    回復,
    無敵,
    発射,
    再生,
    遷移,
    // 制御・システム系
    停止,
    再開,
    検索,
    置換,
    描画,
    フェードイン,
    フェードアウト,
    押下,
    通信,
    ログ出力,
    その他(String),
}

#[derive(Debug, Clone)]
pub struct 命令 {
    pub 動詞: 命令種別,
    pub 引数: String,
}

impl FromStr for 命令種別 {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "表示" => Ok(命令種別::表示),
            "読む" => Ok(命令種別::読む),
            "保存" => Ok(命令種別::保存),
            "作成" => Ok(命令種別::作成),
            "削除" => Ok(命令種別::削除),
            "リネーム" => Ok(命令種別::リネーム),
            "ジャンプ" => Ok(命令種別::ジャンプ),
            "移動" => Ok(命令種別::移動),
            "攻撃" => Ok(命令種別::攻撃),
            "再生" => Ok(命令種別::再生),
            "検索" => Ok(命令種別::検索),
            "ディレクトリ内の画像を表示" => Ok(命令種別::ディレクトリ内の画像を表示),
            "ディレクトリの中身を取得" => Ok(命令種別::ディレクトリの中身を取得),
            _ => Ok(命令種別::その他(s.to_string())),
        }
    }
}
