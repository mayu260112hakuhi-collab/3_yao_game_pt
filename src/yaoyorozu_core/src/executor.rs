use crate::command::{命令, 命令種別};

/// 解析された命令を実行ログや内部状態として出力するテスト用エグゼキューター
pub fn 命令を実行(命令: 命令) {
    match 命令.動詞 {
        命令種別::表示 => println!("【表示】 {}", 命令.引数),
        命令種別::ジャンプ => {
            println!("【アクション】 ジャンプを実行！ パラメータ: {}", 命令.引数)
        }
        命令種別::移動 => println!("【アクション】 {} へ移動", 命令.引数),
        命令種別::攻撃 => println!("【アクション】 攻撃を実行！ 技名: {}", 命令.引数),
        命令種別::再生 => println!("【演出】 アニメーション再生: {}", 命令.引数),
        命令種別::ログ出力 => println!("【ログ】 {}", 命令.引数),
        命令種別::その他(詳細) => println!("【汎用命令】 {}: {}", 詳細, 命令.引数),
        _ => println!("【未実装の命令】 {:?}: {}", 命令.動詞, 命令.引数),
    }
}
