#![allow(non_snake_case)]

use std::fmt;
use std::str::FromStr;

#[derive(Debug, Clone, PartialEq)]
pub enum 値 {
    文字列(String),
    数値(f64),
    真偽(bool),
    記号(String),
    なし,
}

impl 値 {
    pub fn 表示文字列(&self) -> String {
        match self {
            値::文字列(v) => v.clone(),
            値::数値(v) => {
                if v.fract() == 0.0 {
                    format!("{}", *v as i64)
                } else {
                    v.to_string()
                }
            }
            値::真偽(v) => {
                if *v { "真".to_string() } else { "偽".to_string() }
            }
            値::記号(v) => v.clone(),
            値::なし => "なし".to_string(),
        }
    }

    pub fn 真か(&self) -> bool {
        match self {
            値::真偽(v) => *v,
            値::数値(v) => *v != 0.0,
            値::文字列(v) | 値::記号(v) => !v.is_empty(),
            値::なし => false,
        }
    }
}

impl fmt::Display for 値 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.表示文字列())
    }
}

