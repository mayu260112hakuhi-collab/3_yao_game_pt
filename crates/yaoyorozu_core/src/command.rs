#[derive(Debug, Clone, PartialEq)]
pub enum 式 {
    値(値),
    変数(String),
    二項 {
        左: Box<式>,
        演算子: 二項演算子,
        右: Box<式>,
    },
}

#[derive(Debug, Clone, PartialEq)]
pub struct 命令引数 {
    pub 助詞: Option<String>,
    pub 値: 式,
}

#[derive(Debug, Clone, PartialEq)]
pub struct 命令 {
    pub 動詞: 命令種別,
    pub 引数: Vec<命令引数>,
}

impl 命令 {
    pub fn 新規(動詞: 命令種別) -> Self {
        Self {
            動詞,
            引数: Vec::new(),
        }
    }
}

